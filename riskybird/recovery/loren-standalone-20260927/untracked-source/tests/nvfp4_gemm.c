// Bare-metal acceptance test for the NVFP4 RoCC accelerator (custom0).
//
// What it proves, when it can finally be run: that the engine's raw 64-bit
// fixed-point accumulators are *bit-identical* to the frozen vectors in
//   /scratch2/loren/modelblaster/tests/nvfp4_vectors/nvfp4_gemms.hex
// which were harvested from a shipped NVIDIA NVFP4 checkpoint
// (nvidia/Nemotron-3-Embed-1B-NVFP4) and cross-checked against NVIDIA's own
// modelopt dequantizer. That file is the tier-0 external anchor of the whole
// verification chain; this binary is the phase-2/phase-6 tier of it.
//
// The comparison is an EXACT INTEGER COMPARE. There is no tolerance and there
// must never be one. An NVFP4 block dot product contains no rounding at all
// (design doc section 0: every E2M1 magnitude is a multiple of 1/2, so 2|x| is
// an integer and a 16-element block sum is an exact 13-bit integer), and the
// fixed-point accumulator with LSB 2^-20 makes accumulation associative
// (section 3.4). So `max_abs_err` below is 0 on a pass, full stop. A nonzero
// value is a hardware bug, never noise, and inventing an atol to absorb it
// would destroy the only claim this accelerator is being built to support.
//
// It runs every case TWICE. Once with the whole K in a single COMPUTE, and
// once -- for every case with K >= 32, i.e. at least two 16-element blocks --
// as two half-K passes, COMPUTE then COMPUTE_ACC, against the SAME frozen
// expectations. That second run is design doc section 6 phase 2 and it is the
// system-level proof of section 3.3: because the accumulator is integer
// addition of exact terms, where K is split cannot change a single bit. If the
// split run ever needed a different expectation set, or a tolerance, the
// accelerator's whole reason for existing would be gone. Both runs feed one
// MODELBLASTER_VERIFY summary.
//
// It also reports accelerator-busy cycles per dispatch via COUNTER (funct7
// 126), alongside the rdcycle-based wall total. The two measure different
// things: the counter is engine-busy cycles, the wall total includes the
// core's own printf and compare loops.
//
// Issue sequence follows design doc section 4.4. Instruction encodings and
// field packing live in nvfp4.h. MVOUT (funct7 9) is deliberately not issued:
// it is not implemented in RTL v1 and the vectors' OUT column uses a different
// global-scale convention from the ISA (see nvfp4.h's scope note).
//
// NOTE ON RUNNING IT: the accelerator RTL does not exist yet, so this binary
// cannot execute -- the custom0 instructions will trap. Its acceptance test
// today is that it compiles and that `riscv64-unknown-elf-objdump -d` shows
// the .insn encodings coming out as intended.

